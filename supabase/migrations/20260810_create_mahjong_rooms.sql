create or replace function public.mahjong_pick_city(p_mode text)
returns jsonb language plpgsql volatile security definer set search_path = public as $$
declare v_mode text; v_effect public.mahjong_effects%rowtype;
begin
  v_mode := case when random() < 0.5 then 'universal' else p_mode end;
  select * into strict v_effect from public.mahjong_effects
    where kind = 'city' and mode = v_mode order by random() limit 1;
  return jsonb_build_object('name',v_effect.name,'effect',v_effect.effect_text,'origin',v_effect.origin);
end $$;

create or replace function public.mahjong_pick_rarity()
returns text language plpgsql volatile security definer set search_path = public as $$
declare v_roll double precision := random();
begin
  return case when v_roll < 0.5 then 'silver' when v_roll < 0.85 then 'gold' else 'prismatic' end;
end $$;

create or replace function public.mahjong_pick_candidates(p_mode text, p_rarity text)
returns jsonb language plpgsql volatile security definer set search_path = public as $$
declare v_first public.mahjong_effects%rowtype; v_second public.mahjong_effects%rowtype; v_third public.mahjong_effects%rowtype;
begin
  select * into strict v_first from public.mahjong_effects
    where kind='augment' and mode='universal' and rarity=p_rarity order by random() limit 1;
  select * into strict v_second from public.mahjong_effects
    where kind='augment' and mode=p_mode and rarity=p_rarity order by random() limit 1;
  select * into strict v_third from public.mahjong_effects
    where kind='augment' and mode in ('universal',p_mode) and rarity=p_rarity
      and name not in (v_first.name,v_second.name) order by random() limit 1;
  return jsonb_build_array(
    jsonb_build_object('name',v_first.name,'effect',v_first.effect_text,'origin',v_first.origin),
    jsonb_build_object('name',v_second.name,'effect',v_second.effect_text,'origin',v_second.origin),
    jsonb_build_object('name',v_third.name,'effect',v_third.effect_text,'origin',v_third.origin)
  );
end $$;

create or replace function public.mahjong_room_public(p_code text)
returns jsonb language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'code',r.code,'mode',r.mode,'city',r.city,'rarity',r.rarity,'round',r.round,
    'players',coalesce((
      select jsonb_agg(
        jsonb_build_object('seat',p.seat,'selected',p.selected)
        order by case p.seat when '东' then 1 when '南' then 2 when '西' then 3 else 4 end
      )
      from public.mahjong_room_players p where p.room_code=r.code
    ),'[]'::jsonb)
  ) from public.mahjong_rooms r where r.code=p_code;
$$;

create or replace function public.mahjong_create_room(p_mode text)
returns jsonb language plpgsql volatile security definer set search_path = public as $$
declare v_code text; v_host uuid := gen_random_uuid(); v_inserted integer := 0; v_rarity text; v_try integer;
begin
  if p_mode not in ('longyan','xiamen') then raise exception 'invalid_mode'; end if;
  v_rarity := public.mahjong_pick_rarity();
  for v_try in 1..20 loop
    v_code := lpad(floor(random()*1000000)::integer::text,6,'0');
    insert into public.mahjong_rooms(code,mode,city,rarity,host_token)
      values(v_code,p_mode,public.mahjong_pick_city(p_mode),v_rarity,v_host)
      on conflict do nothing;
    get diagnostics v_inserted = row_count;
    exit when v_inserted = 1;
  end loop;
  if v_inserted <> 1 then raise exception 'room_creation_failed'; end if;
  return jsonb_build_object('room',public.mahjong_room_public(v_code),'hostToken',v_host::text);
end $$;

create or replace function public.mahjong_get_room(p_code text)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare v_room jsonb;
begin
  v_room := public.mahjong_room_public(p_code);
  if v_room is null then raise exception 'room_not_found'; end if;
  return jsonb_build_object('room',v_room);
end $$;

create or replace function public.mahjong_join_room(p_code text, p_seat text, p_token uuid)
returns jsonb language plpgsql volatile security definer set search_path = public as $$
declare v_room public.mahjong_rooms%rowtype; v_player public.mahjong_room_players%rowtype;
begin
  if p_seat not in ('东','南','西','北') then raise exception 'invalid_seat'; end if;
  select * into v_room from public.mahjong_rooms where code=p_code;
  if not found then raise exception 'room_not_found'; end if;
  insert into public.mahjong_room_players(room_code,seat,seat_token,candidates)
    values(p_code,p_seat,p_token,public.mahjong_pick_candidates(v_room.mode,v_room.rarity))
    on conflict do nothing;
  select * into strict v_player from public.mahjong_room_players where room_code=p_code and seat=p_seat;
  if v_player.seat_token <> p_token then raise exception 'seat_taken'; end if;
  return jsonb_build_object('seat',v_player.seat,'candidates',v_player.candidates,'selected',v_player.selected,'round',v_room.round);
end $$;

create or replace function public.mahjong_select_hex(p_code text, p_seat text, p_token uuid, p_choice_index integer)
returns jsonb language plpgsql volatile security definer set search_path = public as $$
declare v_player public.mahjong_room_players%rowtype; v_choice jsonb;
begin
  select * into v_player from public.mahjong_room_players where room_code=p_code and seat=p_seat;
  if not found or v_player.seat_token <> p_token then raise exception 'seat_verification_failed'; end if;
  if v_player.selected is not null then raise exception 'already_selected'; end if;
  if p_choice_index not between 0 and 2 then raise exception 'invalid_choice'; end if;
  v_choice := v_player.candidates -> p_choice_index;
  if v_choice is null then raise exception 'invalid_choice'; end if;
  update public.mahjong_room_players set selected=v_choice where room_code=p_code and seat=p_seat;
  return jsonb_build_object('selected',v_choice);
end $$;

create or replace function public.mahjong_next_round(p_code text, p_host_token uuid)
returns jsonb language plpgsql volatile security definer set search_path = public as $$
declare v_room public.mahjong_rooms%rowtype; v_rarity text;
begin
  select * into v_room from public.mahjong_rooms where code=p_code;
  if not found then raise exception 'room_not_found'; end if;
  if v_room.host_token <> p_host_token then raise exception 'host_verification_failed'; end if;
  v_rarity := public.mahjong_pick_rarity();
  update public.mahjong_rooms
    set city=public.mahjong_pick_city(v_room.mode),rarity=v_rarity,round=round+1
    where code=p_code;
  update public.mahjong_room_players
    set candidates=public.mahjong_pick_candidates(v_room.mode,v_rarity),selected=null
    where room_code=p_code;
  return jsonb_build_object('ok',true,'round',v_room.round+1);
end $$;

