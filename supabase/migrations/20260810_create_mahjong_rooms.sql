create extension if not exists pgcrypto;

create table public.mahjong_effects (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('city', 'augment')),
  mode text not null check (mode in ('universal', 'longyan', 'xiamen')),
  rarity text check (rarity in ('silver', 'gold', 'prismatic')),
  name text not null,
  effect_text text not null,
  origin text not null,
  unique nulls not distinct (kind, mode, rarity, name)
);

create table public.mahjong_rooms (
  code text primary key check (code ~ '^[0-9]{6}$'),
  mode text not null check (mode in ('longyan', 'xiamen')),
  city jsonb not null,
  rarity text not null check (rarity in ('silver', 'gold', 'prismatic')),
  round integer not null default 1,
  host_token uuid not null,
  created_at timestamptz not null default now()
);

create table public.mahjong_room_players (
  room_code text not null references public.mahjong_rooms(code) on delete cascade,
  seat text not null check (seat in ('东', '南', '西', '北')),
  seat_token uuid not null,
  candidates jsonb not null,
  selected jsonb,
  joined_at timestamptz not null default now(),
  primary key (room_code, seat)
);

create index mahjong_rooms_created_at_idx on public.mahjong_rooms(created_at);

